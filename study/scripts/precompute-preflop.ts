// Writes src/engine/preflopEquity.ts: all-in equity of each hand class against a random hand.
import { writeFileSync } from 'node:fs';
import { EquitySim, singleCombo, type WeightedCombo } from '../src/engine/equity';
import { HAND_KEYS, keyCombos } from '../src/engine/ranges';
import { mulberry32 } from '../src/engine/rng';

const TRIALS = Number(process.argv[2] ?? 200000);
const rng = mulberry32(20261101);
const anyHand: WeightedCombo[] = [];
for (let a = 0; a < 52; a++) for (let b = 0; b < a; b++) anyHand.push({ a, b, w: 1 });

const out: Record<string, number> = {};
for (const key of HAND_KEYS) {
  const [a, b] = keyCombos(key)[0];
  const sim = new EquitySim([singleCombo(a, b), anyHand], [], [], rng);
  sim.runMonteCarlo(TRIALS);
  out[key] = +sim.result().equity[0].toFixed(4);
}

const body = HAND_KEYS.map((k) => `  ${JSON.stringify(k)}: ${out[k]},`).join('\n');
writeFileSync(
  new URL('../src/engine/preflopEquity.ts', import.meta.url),
  `// Generated by scripts/precompute-preflop.ts (${TRIALS} trials per class). Equity vs. a random hand.\nexport const PREFLOP_EQUITY: Record<string, number> = {\n${body}\n};\n`,
);
console.log('AA', out.AA, 'AKs', out.AKs, '72o', out['72o']);
